/* Optional sound effects. Off by default (settings.sounds). The clips are tiny
   vendored WAV files under /assets/sounds, generated by scripts in the repo;
   nothing is fetched from anywhere else. */

const FILES = {
  correct: '/assets/sounds/correct.wav',
  wrong: '/assets/sounds/wrong.wav',
  complete: '/assets/sounds/complete.wav',
};

const cache = new Map();

export function play(name, enabled) {
  if (!enabled || !FILES[name]) return;
  try {
    let audio = cache.get(name);
    if (!audio) {
      audio = new Audio(FILES[name]);
      audio.preload = 'auto';
      audio.volume = 0.5;
      cache.set(name, audio);
    }
    audio.currentTime = 0;
    const p = audio.play();
    if (p && typeof p.catch === 'function') p.catch(() => {});
  } catch { /* autoplay policy or no audio device */ }
}
