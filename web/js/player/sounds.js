/* Optional sound effects. On by default (settings.sounds). The clips are tiny
   vendored WAV files under /assets/sounds/<pack>/, generated by
   server/tools/make_sounds.py; nothing is fetched from anywhere else.

   A pack is the equipped shop item (me.equipped.sounds: { asset, steps }).
   A pack with `steps` has one correct sound per step of a run of correct
   answers (correct-1.wav .. correct-<steps>.wav, Combo Climb). */

const DEFAULT_PACK = { asset: 'classic', steps: 0 };
const cache = new Map();

function url(pack, name, step) {
  const p = pack && pack.asset ? pack : DEFAULT_PACK;
  if (name === 'correct' && p.steps) {
    const n = Math.min(p.steps, Math.max(1, step || 1));
    return `/assets/sounds/${p.asset}/correct-${n}.wav`;
  }
  return `/assets/sounds/${p.asset}/${name}.wav`;
}

/** play('correct' | 'wrong' | 'complete', enabled, { pack, step }) */
export function play(name, enabled, { pack = null, step = 1 } = {}) {
  if (!enabled) return;
  const src = url(pack, name, step);
  try {
    let audio = cache.get(src);
    if (!audio) {
      audio = new Audio(src);
      audio.preload = 'auto';
      audio.volume = 0.5;
      cache.set(src, audio);
    }
    audio.currentTime = 0;
    const p = audio.play();
    if (p && typeof p.catch === 'function') p.catch(() => {});
  } catch { /* autoplay policy or no audio device */ }
}

/** Shop preview: the pack's sounds in turn (a climb plays its first four steps). */
export function preview(pack) {
  const steps = pack.steps ? [1, 2, 3, 4].map((s) => ['correct', s]) : [['correct', 1]];
  const seq = [...steps, ['wrong', 1], ['complete', 1]];
  seq.forEach(([name, step], i) => setTimeout(() => play(name, true, { pack, step }), i * 520));
  return seq.length * 520;
}
